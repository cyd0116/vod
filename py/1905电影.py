    def custom_removeHtml(self, txt):
        txt = re.sub(r'<script[\s\S]*?</script>', '', str(txt or ''), flags=re.I)
        txt = re.sub(r'<style[\s\S]*?</style>', '', txt, flags=re.I)
        txt = re.sub(r'<[^>]+>', '', txt)
        txt = txt.replace('&nbsp;', ' ').replace('&amp;', '&').replace('\r\n', '\n')
        return re.sub(r'[ \t]+', ' ', txt).strip()

