    def _parse_www(self, root):
        """www 首页(grid-2x) / 分类页(search-list)：不再丢弃 vip 链接"""
        videos = []
        if root is None:
            return videos
        nodes = root.xpath("//div[@class='grid-2x']/a | "
                           "//section[contains(@class,'search-list')]/div/a | "
                           "//div[@class='mod']/div[1]/a")
        for a in nodes:
            try:
                href = (a.xpath('./@href') or [''])[0]
                imgs = a.xpath('./img')
                img_el = imgs[0] if imgs else None
                if img_el is None:
                    continue
                srcs = img_el.xpath('./@src')
                if not srcs or 'lazyImg' in srcs[0]:
                    srcs = img_el.xpath('./@data-lazysrc') or img_el.xpath('./@data-src')
                pic = self._abs(srcs[0]) if srcs else ''
                title = (img_el.xpath('./@alt') or a.xpath('./@title') or
                         img_el.xpath('./h3/text()') or [''])[0].strip()
                if not title or not href:
                    continue
                url = self._abs(href)
                if 'vip.1905.com/play/' in url:
                    vid = url                       # 完整 URL -> VIP 解析线路
                    remark = 'VIP解析'
                else:
                    cid = self.regStr(url, r'/vod/play/(\d+)\.s?html')
                    vid = cid if cid else url       # 数字 id -> 免费直连；否则进详情页再找
                    remark = ''
                videos.append(self._item(vid, title, pic, remark))
            except Exception:
                continue
        return videos

    def _parse_vip(self, root):
        """vip 列表页 / 搜索页通用：图片为 data-lazysrc 懒加载"""
        videos = []
        if root is None:
            return videos
        nodes = root.xpath("//a[contains(@class,'img') and contains(@href,'/play/')]")
        for a in nodes:
            try:
                href = (a.xpath('./@href') or [''])[0]
                if '/play/' not in href:
                    continue
                title = (a.xpath('./@title') or a.xpath('./img/@alt') or [''])[0].strip()
                pics = (a.xpath('./img/@data-lazysrc') or a.xpath('./img/@data-src') or
                        a.xpath('./img/@src') or [''])
                pic = self._abs(pics[0]) if pics and 'lazyImg' not in pics[0] else ''
                if not title or not href:
                    continue
                url = self._abs(href, self.VIP)
                remark_node = a.xpath('./span[contains(@class,"score")]/text()')
                remark = ('评分 ' + remark_node[0].strip()) if remark_node else 'VIP解析'
                videos.append(self._item(url, title, pic, remark))
            except Exception:
                continue
        return videos

    def _parse_search(self, root):
        """www 搜索结果（main clearfix 块）"""
        videos = []
        if root is None:
            return videos
        for div in root.xpath("//div[@class='main clearfix']"):
            try:
                img = (div.xpath('./div[@class="movie-pic"]/a[@class="img-a"]/img') or [None])[0]
                if img is None:
                    continue
                title = (img.xpath('./@alt') or img.xpath('./@title') or [''])[0].strip()
                pics = img.xpath('./@src') or img.xpath('./@data-src')
                pic = self._abs(pics[0]) if pics else ''
                links = (div.xpath('./ul[@class="cont"]/li[contains(@class,"paly-tab-icon")]/a/@href') or
                         div.xpath('./ul[@class="cont"]/li[contains(@class,"position-icon")]/a/@href'))
                fallback = div.xpath('./div[@class="movie-pic"]/a[@class="img-a"]/@href')
                href = links[0] if links else (fallback[0] if fallback else '')
                if not title or not href:
                    continue
                url = self._abs(href)
                if 'vip.1905.com/play/' in url:
                    vid, remark = url, 'VIP解析'
                else:
                    cid = self.regStr(url, r'/vod/play/(\d+)\.s?html')
                    vid, remark = (cid if cid else url), ''
                videos.append(self._item(vid, title, pic, remark))
            except Exception:
                continue
        return videos

    def _max_page(self, root, patterns=()):
        """从分页区读取最大页码，替代硬编码 pagecount。
        兼容 www 的 /o3p99.html、vip 的 /p48o6.shtml、搜索的 ?page=99。"""
        maximum = 1
        if root is None:
            return maximum
        pats = list(patterns) + [
            r'o\d+p(\d+)\.s?html',        # www 分类: /vod/list/n_1/o3p99.html
            r'/p(\d+)o\d+\.s?html',       # vip 分类: /list/t_1/p48o6.shtml
            r'[?&]page=(\d+)',            # 搜索分页
        ]
        hrefs = []
        for xp in ('//section[@id="vod-page"]//a/@href',
                   '//div[@class="pagination"]//a/@href',
                   '//div[@id="new_page"]//a/@href'):
            hrefs.extend(root.xpath(xp))
        for h in hrefs:
            for pat in pats:
                v = self.regStr(h, pat)
                if v.isdigit():
                    maximum = max(maximum, int(v))
        return min(maximum, 9999)

